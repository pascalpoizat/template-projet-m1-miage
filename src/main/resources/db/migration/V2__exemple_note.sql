CREATE TABLE note (
    id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titre   VARCHAR(120) NOT NULL,
    contenu TEXT         NOT NULL,
    CONSTRAINT ck_note_titre CHECK (LENGTH(TRIM(titre)) > 0)
);
